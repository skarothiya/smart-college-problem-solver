-- ---------- profiles ----------

DROP POLICY IF EXISTS "profiles_select_authenticated" ON public.profiles;
CREATE POLICY "profiles_select_authenticated"
  ON public.profiles
  FOR SELECT
  TO authenticated
  USING (
    auth.uid() = id
    OR public.is_student()
    OR public.is_admin()
  );

DROP POLICY IF EXISTS "profiles_insert_student_self" ON public.profiles;
CREATE POLICY "profiles_insert_student_self"
  ON public.profiles
  FOR INSERT
  TO authenticated
  WITH CHECK (
    auth.uid() = id
    AND role = 'student'
  );

DROP POLICY IF EXISTS "profiles_update_student_own" ON public.profiles;
CREATE POLICY "profiles_update_student_own"
  ON public.profiles
  FOR UPDATE
  TO authenticated
  USING (
    auth.uid() = id
    AND role = 'student'
  )
  WITH CHECK (
    auth.uid() = id
    AND role = 'student'
  );

DROP POLICY IF EXISTS "profiles_update_admin_own" ON public.profiles;
CREATE POLICY "profiles_update_admin_own"
  ON public.profiles
  FOR UPDATE
  TO authenticated
  USING (
    auth.uid() = id
    AND public.is_admin()
  )
  WITH CHECK (
    auth.uid() = id
    AND role = 'admin'
  );

-- No public INSERT for admin role — create admin users via Supabase Dashboard / SQL only.

-- ---------- complaints ----------

DROP POLICY IF EXISTS "complaints_select_authenticated" ON public.complaints;
CREATE POLICY "complaints_select_authenticated"
  ON public.complaints
  FOR SELECT
  TO authenticated
  USING (
    public.is_student() OR public.is_admin()
  );

DROP POLICY IF EXISTS "complaints_insert_student_own" ON public.complaints;
CREATE POLICY "complaints_insert_student_own"
  ON public.complaints
  FOR INSERT
  TO authenticated
  WITH CHECK (
    public.is_student()
    AND auth.uid() = user_id
    AND status = 'Pending'
  );

DROP POLICY IF EXISTS "complaints_update_admin_status" ON public.complaints;
CREATE POLICY "complaints_update_admin_status"
  ON public.complaints
  FOR UPDATE
  TO authenticated
  USING (public.is_admin())
  WITH CHECK (public.is_admin());

-- Students cannot UPDATE or DELETE complaints (status changes are admin-only).

-- ---------- upvotes ----------

DROP POLICY IF EXISTS "upvotes_select_own" ON public.upvotes;
CREATE POLICY "upvotes_select_own"
  ON public.upvotes
  FOR SELECT
  TO authenticated
  USING (
    auth.uid() = user_id
    AND public.is_student()
  );

DROP POLICY IF EXISTS "upvotes_select_admin" ON public.upvotes;
CREATE POLICY "upvotes_select_admin"
  ON public.upvotes
  FOR SELECT
  TO authenticated
  USING (public.is_admin());

DROP POLICY IF EXISTS "upvotes_insert_student_own" ON public.upvotes;
CREATE POLICY "upvotes_insert_student_own"
  ON public.upvotes
  FOR INSERT
  TO authenticated
  WITH CHECK (
    public.is_student()
    AND auth.uid() = user_id
  );

-- Students cannot delete upvotes in current app; no DELETE policy for students.

-- ---------- notifications ----------

DROP POLICY IF EXISTS "notifications_select_own" ON public.notifications;
CREATE POLICY "notifications_select_own"
  ON public.notifications
  FOR SELECT
  TO authenticated
  USING (auth.uid() = user_id);

DROP POLICY IF EXISTS "notifications_update_own" ON public.notifications;
CREATE POLICY "notifications_update_own"
  ON public.notifications
  FOR UPDATE
  TO authenticated
  USING (auth.uid() = user_id)
  WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "notifications_insert_admin" ON public.notifications;
CREATE POLICY "notifications_insert_admin"
  ON public.notifications
  FOR INSERT
  TO authenticated
  WITH CHECK (public.is_admin());

